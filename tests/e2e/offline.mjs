import { browser, login, photo, BASE, ADMIN_USER, FIELD_PASS } from './cdp.mjs';
const ck = await login('somsak', FIELD_PASS);
const office = await login(ADMIN_USER, process.env.ADMIN_PASS);
const get = async (p, cookie = ck) => (await fetch(BASE + p, { headers: { cookie: 'cct_s=' + cookie } })).json();
const f = await get('/api/field');
const c = f.crew.find(x => x.name === 'Tran Minh Duc');
const doneBefore = c.cps.filter(x => x.actual).length, photosBefore = c.photos.length;
const next = c.cps.find(x => x.actual == null), needPhoto = !!next.need_photo && !c.photos.some(p => p.cp_idx === next.idx);
const events = async () => (await get('/api/jobs/' + c.job_id, office)).activity.filter(a => a.kind === 'cp' && a.text.startsWith(`${c.name} · ${next.name}`)).length;
const eventsBefore = await events();
const b = await browser();
const sleep = ms => new Promise(r => setTimeout(r, ms));
await b.size(390, 800, true);
await b.go('/api/health', 200);
await b.cookie(ck);
await b.go('/field/' + c.id, 1800);
await b.send('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
// A point that needs a photo queues the photo and the confirmation together; other points queue the confirmation alone.
if (needPhoto) await b.eval(`(() => { const dt = new DataTransfer(); dt.items.add(new File([Uint8Array.from(atob(${JSON.stringify(photo().toString('base64'))}), x => x.charCodeAt(0))], 'offline.jpg', { type: 'image/jpeg' })); const i = document.querySelector('[data-chg="f-snap"]'); i.files = dt.files; i.dispatchEvent(new Event('change', { bubbles: true })); })()`);
else await b.eval(`document.querySelector('[data-act="f-confirm"]').click()`);
const want = needPhoto ? 2 : 1;
for (let i = 0; i < 60 && JSON.parse(await b.eval(`localStorage.getItem('cct-outbox-v1')`) || '[]').length < want; i++) await sleep(250);
await sleep(600);
const box = await b.eval(`localStorage.getItem('cct-outbox-v1')`);
const toast = await b.eval(`document.getElementById('toast').textContent`);
const pendUi = await b.eval(`!!document.querySelector('.tli .pend')`);
const serverWhileOffline = (await get('/api/field')).crew.find(x => x.id === c.id).cps.filter(x => x.actual).length;
await b.send('Network.emulateNetworkConditions', { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
await b.eval(`window.dispatchEvent(new Event('online'))`);
await sleep(3000);
const after = (await get('/api/field')).crew.find(x => x.id === c.id);
const box2 = await b.eval(`localStorage.getItem('cct-outbox-v1')`);
const items = JSON.parse(box || '[]'), shot = after.photos.find(p => p.cp_idx === next.idx), point = after.cps[next.idx];
const r = { needPhoto, queued: items.length, toast, pendUi, serverWhileOffline, doneBefore, serverAfter: after.cps.filter(x => x.actual).length, photosAdded: after.photos.length - photosBefore, sameTime: !needPhoto || (!!shot && Math.abs(shot.at - point.actual) < 2000 && items.every(x => x.at === items[0].at)), eventsAdded: await events() - eventsBefore, outboxAfter: box2, logs: b.logs };
console.log(r);
b.close();
const good = r.queued === want && r.pendUi && r.serverWhileOffline === doneBefore && r.serverAfter === doneBefore + 1 && JSON.parse(box2 || '[]').length === 0 && r.photosAdded === (needPhoto ? 1 : 0) && r.sameTime && r.eventsAdded === 1 && !b.logs.length;
console.log(good ? 'PASS offline confirm queued and synced' : 'FAIL offline confirm');
if (!good) process.exitCode = 1;
